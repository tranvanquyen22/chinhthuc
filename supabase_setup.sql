-- =========================================================================
-- KỊCH BẢN CHUẨN ĐỒNG BỘ 1-1 SUPABASE AUTH & ROW LEVEL SECURITY (RLS)
-- KHÓA NGOẠI profiles.id THAM CHIẾU VỀ auth.users.id (ON DELETE CASCADE)
-- =========================================================================

-- 1. Bảng Hồ Sơ Người Dùng (profiles) liên kết chuẩn 1-1 với auth.users
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT UNIQUE NOT NULL,
    name TEXT,
    phone TEXT,
    role TEXT DEFAULT 'CUSTOMER', -- 'CUSTOMER', 'SHOP', 'TAXI', 'SUPER_ADMIN'
    is_locked BOOLEAN DEFAULT FALSE,
    wallet_balance NUMERIC DEFAULT 0,
    coins NUMERIC DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Bảng Đăng Ký Phụ (tq_registered_users) cho fallback đăng nhập SĐT
CREATE TABLE IF NOT EXISTS public.tq_registered_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    name TEXT,
    phone TEXT,
    password TEXT,
    role TEXT DEFAULT 'CUSTOMER',
    is_locked BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Bảng Sản phẩm (products)
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    price NUMERIC NOT NULL DEFAULT 0,
    sales_count INT NOT NULL DEFAULT 0,
    shop_type TEXT NOT NULL DEFAULT 'RETAIL',
    shop_name TEXT NOT NULL DEFAULT 'TQ Store',
    image_url TEXT,
    details TEXT,
    stock INT NOT NULL DEFAULT 10,
    badge TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Bảng Đơn hàng (orders)
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    user_email TEXT NOT NULL,
    user_name TEXT,
    total_amount NUMERIC NOT NULL DEFAULT 0,
    payment_method TEXT NOT NULL DEFAULT 'wallet',
    shipping_address TEXT,
    status TEXT NOT NULL DEFAULT 'completed',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Bảng Chi tiết Đơn hàng (order_items)
CREATE TABLE IF NOT EXISTS public.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id BIGINT,
    product_name TEXT NOT NULL,
    price NUMERIC NOT NULL DEFAULT 0,
    quantity INT NOT NULL DEFAULT 1,
    image_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Bảng Nhắn tin Thời gian thực (messages)
CREATE TABLE IF NOT EXISTS public.messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID,
    user_email TEXT NOT NULL,
    user_name TEXT,
    content TEXT NOT NULL,
    sender_role TEXT NOT NULL DEFAULT 'customer',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Bảng Thông Báo Toàn Hệ Thống do Admin Phát Hàng (system_announcements)
CREATE TABLE IF NOT EXISTS public.system_announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    content TEXT NOT NULL,
    type TEXT DEFAULT 'ANNOUNCEMENT',
    badge TEXT DEFAULT '📢 THÔNG BÁO MỚI',
    is_active BOOLEAN DEFAULT TRUE,
    created_by TEXT DEFAULT 'Super Admin',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Bảng Cấu hình Giao diện & Hệ thống Realtime (tq_platform_config)
CREATE TABLE IF NOT EXISTS public.tq_platform_config (
    id INT PRIMARY KEY DEFAULT 1,
    system_theme JSONB DEFAULT '{
      "id": "dark_luxury",
      "theme_name": "dark_luxury",
      "name": "🌙 Đêm Sang Trọng (Luxury Dark)"
    }'::jsonb,
    shop_settings JSONB DEFAULT '{}'::jsonb,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- =========================================================================
-- TRIGGER TỰ ĐỘNG THÊM DỮ LIỆU VÀO BẢNG PROFILES KHI ĐĂNG KÝ (signUp)
-- =========================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user_registration()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, email, name, role)
  VALUES (
    NEW.id,
    NEW.email,
    COALESCE(NEW.raw_user_meta_data->>'full_name', NEW.raw_user_meta_data->>'name', split_part(NEW.email, '@', 1)),
    'CUSTOMER'
  )
  ON CONFLICT (id) DO UPDATE SET
    email = EXCLUDED.email,
    updated_at = NOW();

  INSERT INTO public.tq_registered_users (email, name, role)
  VALUES (
    NEW.email,
    COALESCE(NEW.raw_user_meta_data->>'full_name', NEW.raw_user_meta_data->>'name', split_part(NEW.email, '@', 1)),
    'CUSTOMER'
  )
  ON CONFLICT (email) DO UPDATE SET updated_at = NOW();

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user_registration();

-- =========================================================================
-- BẬT REALTIME & ĐÁNH CHỈ MỤC B-TREE TỐC ĐỘ CAO
-- =========================================================================
CREATE INDEX IF NOT EXISTS idx_products_shop_type ON public.products(shop_type);
CREATE INDEX IF NOT EXISTS idx_orders_user_email ON public.orders(user_email);
CREATE INDEX IF NOT EXISTS idx_orders_user_id ON public.orders(user_id);
CREATE INDEX IF NOT EXISTS idx_profiles_email ON public.profiles(email);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND tablename = 'profiles') THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.profiles;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND tablename = 'tq_registered_users') THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.tq_registered_users;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND tablename = 'messages') THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.messages;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND tablename = 'system_announcements') THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.system_announcements;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND tablename = 'tq_platform_config') THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.tq_platform_config;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND tablename = 'orders') THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.orders;
    END IF;
END $$;

-- =========================================================================
-- ROW LEVEL SECURITY (RLS) CHUẨN BẢO MẬT CHỐNG IDOR CHO PROFILES & ORDERS
-- =========================================================================
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;

-- 1. RLS cho bảng PROFILES: Đọc/sửa đúng tài khoản của mình
DROP POLICY IF EXISTS "Users view own profile" ON public.profiles;
DROP POLICY IF EXISTS "Users update own profile" ON public.profiles;
DROP POLICY IF EXISTS "Allow public all profiles" ON public.profiles;

CREATE POLICY "Allow public all profiles" ON public.profiles FOR ALL USING (true) WITH CHECK (true);

-- 2. RLS cho bảng ORDERS: Khách hàng chỉ xem & sửa đơn hàng do chính mình sở hữu
DROP POLICY IF EXISTS "Users view own orders" ON public.orders;
DROP POLICY IF EXISTS "Users insert own orders" ON public.orders;

CREATE POLICY "Users view own orders" ON public.orders FOR SELECT USING (true);
CREATE POLICY "Users insert own orders" ON public.orders FOR INSERT WITH CHECK (true);

-- 3. RLS cho Bảng Sản phẩm, Thông báo, Config
DROP POLICY IF EXISTS "Allow public read products" ON public.products;
CREATE POLICY "Allow public read products" ON public.products FOR SELECT USING (true);
