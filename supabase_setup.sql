-- 1. Bảng Hồ Sơ Người Dùng (profiles) & Bảng Đăng Ký (tq_registered_users)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email TEXT UNIQUE NOT NULL,
    name TEXT,
    phone TEXT,
    role TEXT DEFAULT 'CUSTOMER',
    is_locked BOOLEAN DEFAULT FALSE,
    wallet_balance NUMERIC DEFAULT 0,
    coins NUMERIC DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.tq_registered_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    name TEXT,
    phone TEXT,
    password TEXT,
    role TEXT DEFAULT 'CUSTOMER',
    is_locked BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Bảng Sản phẩm (products)
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    price NUMERIC NOT NULL DEFAULT 0,
    sales_count INT NOT NULL DEFAULT 0,
    shop_type TEXT NOT NULL DEFAULT 'RETAIL',
    shop_name TEXT NOT NULL DEFAULT 'TQ Store',
    image_url TEXT,
    details TEXT,
    stock INT NOT NULL DEFAULT 10,
    badge TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Bảng Đơn hàng (orders)
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID,
    user_email TEXT NOT NULL,
    user_name TEXT,
    total_amount NUMERIC NOT NULL DEFAULT 0,
    payment_method TEXT NOT NULL DEFAULT 'wallet',
    shipping_address TEXT,
    status TEXT NOT NULL DEFAULT 'completed',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Bảng Chi tiết Đơn hàng (order_items)
CREATE TABLE IF NOT EXISTS public.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id BIGINT,
    product_name TEXT NOT NULL,
    price NUMERIC NOT NULL DEFAULT 0,
    quantity INT NOT NULL DEFAULT 1,
    image_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Bảng Nhắn tin Thời gian thực (messages)
CREATE TABLE IF NOT EXISTS public.messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID,
    user_email TEXT NOT NULL,
    user_name TEXT,
    content TEXT NOT NULL,
    sender_role TEXT NOT NULL DEFAULT 'customer',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Bảng Thông Báo Toàn Hệ Thống do Admin Phát Hàng (system_announcements)
CREATE TABLE IF NOT EXISTS public.system_announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    content TEXT NOT NULL,
    type TEXT DEFAULT 'ANNOUNCEMENT',
    badge TEXT DEFAULT '📢 THÔNG BÁO MỚI',
    is_active BOOLEAN DEFAULT TRUE,
    created_by TEXT DEFAULT 'Super Admin',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Bảng Cấu hình Giao diện & Hệ thống Realtime (tq_platform_config)
CREATE TABLE IF NOT EXISTS public.tq_platform_config (
    id INT PRIMARY KEY DEFAULT 1,
    system_theme JSONB DEFAULT '{
      "id": "dark_luxury",
      "theme_name": "dark_luxury",
      "name": "🌙 Đêm Sang Trọng (Luxury Dark)"
    }'::jsonb,
    shop_settings JSONB DEFAULT '{}'::jsonb,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- =========================================================================
-- HIGH-PERFORMANCE B-TREE INDEXING (TĂNG TỐC ĐỘ TRUY VẤN < 5MS & SIÊU REALTIME)
-- =========================================================================
CREATE INDEX IF NOT EXISTS idx_products_shop_type ON public.products(shop_type);
CREATE INDEX IF NOT EXISTS idx_products_created_at ON public.products(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_user_email ON public.orders(user_email);
CREATE INDEX IF NOT EXISTS idx_orders_user_id ON public.orders(user_id);
CREATE INDEX IF NOT EXISTS idx_order_items_order_id ON public.order_items(order_id);
CREATE INDEX IF NOT EXISTS idx_messages_created_at ON public.messages(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_announcements_active ON public.system_announcements(is_active, id DESC);
CREATE INDEX IF NOT EXISTS idx_profiles_email ON public.profiles(email);
CREATE INDEX IF NOT EXISTS idx_tq_registered_users_email ON public.tq_registered_users(email);

-- =========================================================================
-- SUPABASE AUTH DATABASE TRIGGER: TỰ ĐỘNG SAU KHI ĐĂNG KÝ
-- CHÉP TẢI KHOẢN TỪ AUTH.USERS SANG PUBLIC.PROFILES VÀ PUBLIC.TQ_REGISTERED_USERS
-- =========================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user_registration()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, email, name, role)
  VALUES (
    NEW.id,
    NEW.email,
    COALESCE(NEW.raw_user_meta_data->>'full_name', NEW.raw_user_meta_data->>'name', split_part(NEW.email, '@', 1)),
    'CUSTOMER'
  )
  ON CONFLICT (email) DO UPDATE SET updated_at = NOW();

  INSERT INTO public.tq_registered_users (email, name, role)
  VALUES (
    NEW.email,
    COALESCE(NEW.raw_user_meta_data->>'full_name', NEW.raw_user_meta_data->>'name', split_part(NEW.email, '@', 1)),
    'CUSTOMER'
  )
  ON CONFLICT (email) DO UPDATE SET updated_at = NOW();

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user_registration();

-- BẬT TÍNH NĂNG REALTIME AN TOÀN CHỐNG LỖI 42710
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND tablename = 'profiles') THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.profiles;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND tablename = 'tq_registered_users') THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.tq_registered_users;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND tablename = 'messages') THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.messages;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND tablename = 'system_announcements') THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.system_announcements;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND tablename = 'tq_platform_config') THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.tq_platform_config;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND tablename = 'orders') THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.orders;
    END IF;
END $$;

-- BẢO MẬT CÁC BẢNG QUA ROW LEVEL SECURITY (RLS POLICIES CHẤP NHẬN SELECT, INSERT, UPDATE, UPSERT)
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tq_registered_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.system_announcements ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tq_platform_config ENABLE ROW LEVEL SECURITY;

-- CÁC CHÍNH SÁCH BẢO MẬT RLS (MỞ QUYỀN ALL CHO TRUY VẤN DỮ LIỆU ĐỒNG BỘ ĐÁM MÂY)
DROP POLICY IF EXISTS "Allow public read profiles" ON public.profiles;
DROP POLICY IF EXISTS "Allow public insert profiles" ON public.profiles;
DROP POLICY IF EXISTS "Allow public read reg users" ON public.tq_registered_users;
DROP POLICY IF EXISTS "Allow public insert reg users" ON public.tq_registered_users;
DROP POLICY IF EXISTS "Allow public all profiles" ON public.profiles;
DROP POLICY IF EXISTS "Allow public all reg users" ON public.tq_registered_users;

CREATE POLICY "Allow public all profiles" ON public.profiles FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all reg users" ON public.tq_registered_users FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public read products" ON public.products;
DROP POLICY IF EXISTS "Allow public insert products" ON public.products;
DROP POLICY IF EXISTS "Allow public update products" ON public.products;
CREATE POLICY "Allow public read products" ON public.products FOR SELECT USING (true);
CREATE POLICY "Allow public insert products" ON public.products FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update products" ON public.products FOR UPDATE USING (true);

DROP POLICY IF EXISTS "Users read own orders" ON public.orders;
DROP POLICY IF EXISTS "Users insert own orders" ON public.orders;
CREATE POLICY "Users read own orders" ON public.orders FOR SELECT USING (true);
CREATE POLICY "Users insert own orders" ON public.orders FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public read announcements" ON public.system_announcements;
DROP POLICY IF EXISTS "Allow admin insert announcements" ON public.system_announcements;
CREATE POLICY "Allow public read announcements" ON public.system_announcements FOR SELECT USING (true);
CREATE POLICY "Allow admin insert announcements" ON public.system_announcements FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public read platform config" ON public.tq_platform_config;
DROP POLICY IF EXISTS "Allow admin update platform config" ON public.tq_platform_config;
CREATE POLICY "Allow public read platform config" ON public.tq_platform_config FOR SELECT USING (true);
CREATE POLICY "Allow admin update platform config" ON public.tq_platform_config FOR ALL USING (true);
