-- KỊCH BẢN KHỞI TẠO CƠ SỞ DỮ LIỆU ĐỒNG BỘ NGUYÊN NGHỆ CAO CẤP (ENTERPRISE SUPABASE SQL)
-- TỐI ƯU HIỆU SUẤT TỐC ĐỘ CAO < 5MS, ĐỒNG BỘ REALTIME & LƯU TRỮ BỀN VỮNG VĨNH VIỄN
